#!/usr/bin/env node
// docker/apply/fork-firewall.mjs — the apply container's firewall is the Workspace's, with five
// literal substitutions and nothing else (Phase 23).
//
//   node docker/apply/fork-firewall.mjs --write    regenerate docker/apply/init-firewall.sh
//   node docker/apply/fork-firewall.mjs --check    exit 1 when the committed file has drifted
//
// docker/workspace/init-firewall.sh (Phase 21) is the reviewed script: default-deny egress, one run
// per start, DNS to the container's resolvers only, IPv6 closed, each allowed name pinned to the
// address that was allowed, and an end check. The apply container needs the same rules with one
// database secret instead of two. A second hand-edited copy of a 400-line security script would
// drift, so the fork is generated, and docker/apply/image.test.mjs fails when the committed file is
// not exactly what this produces from the Workspace's script as it is today.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const SOURCE = path.resolve(HERE, '..', 'workspace', 'init-firewall.sh');
export const TARGET = path.join(HERE, 'init-firewall.sh');

/** [what, from, to]: each `from` must occur exactly once in the Workspace's script. */
export const SUBSTITUTIONS = Object.freeze([
  [
    'the header',
    '# Default-deny egress for the Workspace container (brief 102 task 12; P-88).\n',
    '# Default-deny egress for the apply container (Phase 23).\n' +
      '#\n' +
      '# GENERATED by docker/apply/fork-firewall.mjs from docker/workspace/init-firewall.sh: do not edit\n' +
      '# this file, edit that one and run the generator. Five literals differ and nothing else: this\n' +
      '# line, the two ipset names, the run marker, and the database secrets, which here are the one\n' +
      '# secret inbox_apply_db_url. Everything below is the Workspace script\'s own text, so where it says\n' +
      '# the Workspace or the runner, read the apply worker and its one pooler connection: the same\n' +
      '# three names are allowed here (since Phase 24a the Workspace script reads one database secret too).\n',
  ],
  ['the HTTPS set', 'readonly HTTPS_SET=workspace-https\n', 'readonly HTTPS_SET=apply-https\n'],
  ['the Postgres set', 'readonly POSTGRES_SET=workspace-postgres\n', 'readonly POSTGRES_SET=apply-postgres\n'],
  ['the run marker', 'readonly FIREWALL_RUN_MARKER=/dev/shm/bb2dash-workspace-firewall.up\n', 'readonly FIREWALL_RUN_MARKER=/dev/shm/bb2dash-apply-firewall.up\n'],
  [
    'the database secrets',
    'readonly -a DSN_SECRETS=(\n  "workspace_runner_db_url"\n)\n',
    'readonly -a DSN_SECRETS=(\n  "inbox_apply_db_url"\n)\n',
  ],
]);

/** The apply container's script, from the Workspace's. Throws when a literal is not there exactly once. */
export function forkFirewall(source) {
  let text = source.replace(/\r\n/g, '\n');
  for (const [what, from, to] of SUBSTITUTIONS) {
    const count = text.split(from).length - 1;
    if (count !== 1) throw new Error(`fork-firewall: ${what} occurs ${count} times in the Workspace script, expected once`);
    text = text.replace(from, () => to);
  }
  return text;
}

function main(argv) {
  const generated = forkFirewall(fs.readFileSync(SOURCE, 'utf8'));
  if (argv.includes('--write')) {
    fs.writeFileSync(TARGET, generated);
    process.stdout.write(`wrote ${path.relative(process.cwd(), TARGET)}\n`);
    return 0;
  }
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current === generated) return 0;
  process.stdout.write('docker/apply/init-firewall.sh is not what fork-firewall.mjs generates: run it with --write\n');
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
