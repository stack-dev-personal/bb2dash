#!/usr/bin/env node
// docker/workspace-ingest/fork-firewall.mjs — the ingest worker's firewall is the Workspace's, with a
// few literal substitutions and nothing else (Phase 24a, freeze amendment F-3). The pattern is
// docker/apply/fork-firewall.mjs.
//
//   node docker/workspace-ingest/fork-firewall.mjs --write    regenerate docker/workspace-ingest/init-firewall.sh
//   node docker/workspace-ingest/fork-firewall.mjs --check    exit 1 when the committed file has drifted
//
// The worker may reach two names and nothing else: the project host on tcp/443 (the signed download and
// the embed function) and the pooler named in workspace_ingest_db_url on tcp/5432. Not api.anthropic.com:
// the worker holds no model. A second hand-edited copy of a 400-line security script would drift, so the
// fork is generated, and docker/workspace-ingest/image.test.mjs fails when the committed file is not
// exactly what this produces from the Workspace's script as it is today.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const SOURCE = path.resolve(HERE, '..', 'workspace', 'init-firewall.sh');
export const TARGET = path.join(HERE, 'init-firewall.sh');

/** [what, from, to]: each `from` must occur exactly once in the Workspace's script. */
export const SUBSTITUTIONS = Object.freeze([
  [
    'the header',
    '# Default-deny egress for the Workspace container (brief 102 task 12; P-88).\n',
    '# Default-deny egress for the ingest worker (Phase 24a).\n' +
      '#\n' +
      '# GENERATED by docker/workspace-ingest/fork-firewall.mjs from docker/workspace/init-firewall.sh: do not\n' +
      '# edit this file, edit that one and run the generator. Six literals differ and nothing else: this\n' +
      '# line, the list of names in the paragraph below, the two ipset names, the run marker, the list of\n' +
      '# HTTPS names, the database secret, which here is the one secret workspace_ingest_db_url, and the end\n' +
      '# check\'s allowed address. Everything else is the Workspace script\'s own text, so where it says the\n' +
      '# Workspace, the runner or the CLI, read the ingest worker: two names are allowed here, the project\n' +
      '# host and the pooler, and api.anthropic.com is not one of them.\n',
  ],
  [
    'the names in the header',
    '# When it exits 0 the container can reach three names, each on one TCP port, and nothing else:\n' +
      '#\n' +
      '#   api.anthropic.com                   tcp/443   the `claude` CLI, on Stack\'s subscription token\n' +
      '#   goultdzqcavefcgnifdy.supabase.co    tcp/443   the materials MCP server (the bb2dash project\'s API)\n' +
      '#   the host of workspace_runner_db_url tcp/5432  the runner\'s own queue connection (the session pooler)\n',
    '# When it exits 0 the container can reach two names, each on one TCP port, and nothing else:\n' +
      '#\n' +
      '#   goultdzqcavefcgnifdy.supabase.co     tcp/443   the signed download and the embed function\n' +
      '#   the host of workspace_ingest_db_url  tcp/5432  the worker\'s own connection (the session pooler)\n',
  ],
  ['the HTTPS set', 'readonly HTTPS_SET=workspace-https\n', 'readonly HTTPS_SET=ingest-https\n'],
  ['the Postgres set', 'readonly POSTGRES_SET=workspace-postgres\n', 'readonly POSTGRES_SET=ingest-postgres\n'],
  ['the run marker', 'readonly FIREWALL_RUN_MARKER=/dev/shm/bb2dash-workspace-firewall.up\n', 'readonly FIREWALL_RUN_MARKER=/dev/shm/bb2dash-ingest-firewall.up\n'],
  [
    'the HTTPS names',
    'readonly -a HTTPS_HOSTS=(\n  "api.anthropic.com"\n  "goultdzqcavefcgnifdy.supabase.co"\n)\n',
    'readonly -a HTTPS_HOSTS=(\n  "goultdzqcavefcgnifdy.supabase.co"\n)\n',
  ],
  [
    'the database secrets',
    'readonly -a DSN_SECRETS=(\n  "workspace_runner_db_url"\n)\n',
    'readonly -a DSN_SECRETS=(\n  "workspace_ingest_db_url"\n)\n',
  ],
  ['the allowed probe', 'readonly ALLOWED_PROBE=https://api.anthropic.com\n', 'readonly ALLOWED_PROBE=https://goultdzqcavefcgnifdy.supabase.co\n'],
]);

/** The ingest worker's script, from the Workspace's. Throws when a literal is not there exactly once. */
export function forkFirewall(source) {
  let text = source.replace(/\r\n/g, '\n');
  for (const [what, from, to] of SUBSTITUTIONS) {
    const count = text.split(from).length - 1;
    if (count !== 1) throw new Error(`fork-firewall: ${what} occurs ${count} times in the Workspace script, expected once`);
    text = text.replace(from, () => to);
  }
  return text;
}

function main(argv) {
  const generated = forkFirewall(fs.readFileSync(SOURCE, 'utf8'));
  if (argv.includes('--write')) {
    fs.writeFileSync(TARGET, generated);
    process.stdout.write(`wrote ${path.relative(process.cwd(), TARGET)}\n`);
    return 0;
  }
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current === generated) return 0;
  process.stdout.write('docker/workspace-ingest/init-firewall.sh is not what fork-firewall.mjs generates: run it with --write\n');
  return 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
