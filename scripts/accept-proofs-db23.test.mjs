/** The sync, the apply request it filed, and the two answered questions that request archived. */
async function afterSync({ apply = {}, first = {}, second = {} } = {}) {
  const sync = await addSync();
  const request = await addApply({ trigger: 'sync', after: sync, ...apply });
  const confirm = await addItem({ label: 'confirm', by: request, bucket: 'recorded_elsewhere', ...first });
  const dismiss = await addItem({ label: 'dismiss', kind: 'data_gap', by: request, bucket: 'dismissed', resolution: { dismissed: true }, ...second });
  return { sync, request, confirm, dismiss };
}

const afterSyncParams = (world) => ({ sync_request: String(world.sync), first_item: String(world.confirm), second_item: String(world.dismiss), since: SINCE });

test('recorded-after-sync: the sync done, one apply request it filed, taken by the worker and done, archived the two in their buckets', async () => {
  const world = await afterSync();
  const passed = await prove('recorded-after-sync', afterSyncParams(world));
  assert.equal(passed.code, EXIT.pass, passed.why);
  assert.deepEqual(
    [passed.detail.sync_state, passed.detail.apply_requests_naming_it, passed.detail.apply_request_id, passed.detail.apply_filed_by, passed.detail.apply_state],
    ['done', 1, world.request, 'sync', 'done'],
  );
  assert.deepEqual([passed.detail.first_bucket, passed.detail.second_bucket], ['recorded_elsewhere', 'dismissed']);
  assert.equal(passed.detail.apply_claude_started, false);
  await recordedAfterSyncCase2();
  await recordedAfterSyncCase3();
});

