/** Runs one proof of the working tree's Phase 23 pack against the in-process database: its exit code and its one line. */
async function prove(name, params = {}) {
  const out = [];
  const err = [];
  const code = await run(argvForPhase('23', name, params), {
    out: (line) => out.push(line),
    err: (line) => err.push(line),
    readPack: () => PACK_23,
    clientFactory: async () => clientOn(db),
  });
  assert.equal(out.length, 1, 'one line is printed');
  assert.doesNotMatch(out[0], COURSE_TEXT);
  const line = JSON.parse(out[0]);
  return { code, line, detail: line.detail, blocked: line.blocked === true, why: err.join('\n') };
}

async function addRequest({ kind = 'inbox_feedback', state = 'done', params = {}, createdAt = IN_RUN, claimedBy = null, claimedAfterS = null, finishedAfterS = null, result = null }) {
  const row = await db.query(
    `insert into public.agent_requests (kind, state, params, created_at, claimed_by, claimed_at, finished_at, result)
     values ($1, $2, $3::jsonb, $4::timestamptz, $5,
             case when $6::integer is null then null else $4::timestamptz + make_interval(secs => $6::integer) end,
             case when $7::integer is null then null else $4::timestamptz + make_interval(secs => $7::integer) end,
             $8::jsonb)
     returning id`,
    [kind, state, JSON.stringify(params), createdAt, claimedBy, claimedAfterS, finishedAfterS, result === null ? null : JSON.stringify(result)],
  );
  return row.rows[0].id;
}

/** A sync request the sync container took and closed. */
const addSync = (more = {}) => addRequest({ kind: 'sync', state: 'done', claimedBy: 'sync-runner', claimedAfterS: 15, finishedAfterS: 120, ...more });

/** An Inbox apply request: `trigger` null is a press of the button, which files a request with no trigger. */
function addApply({ trigger = 'sync', after = null, state = 'done', claudeStarted = false, error = null, createdAt = IN_RUN, claimedBy = APPLIER, claimedAfterS = 12, finishedAfterS = 40, archived = 2 } = {}) {
  const params = trigger === null ? {} : { trigger, after };
  const result = state === 'done' || state === 'failed' ? { lines: ['A line'], archived, claude: { started: claudeStarted }, ...(error === null ? {} : { error }) } : null;
  return addRequest({
    kind: 'inbox_feedback',
    state,
    params,
    createdAt,
    claimedBy: state === 'queued' ? null : claimedBy,
    claimedAfterS: state === 'queued' ? null : claimedAfterS,
    finishedAfterS: state === 'done' || state === 'failed' ? finishedAfterS : null,
    result,
  });
}

/**
 * One Inbox item. The defaults are a test question as `inbox_accept_question` raises it, answered
 * and archived by `by` (a request id) in the bucket given; `by: null` leaves it open, `state`
 * overrides the state of an answered one that is not archived yet.
 */
async function addItem({
  label, tag = TAG, id = null, kind = 'stack_must_confirm', by = null, bucket = 'recorded_elsewhere', state = null, raisedAt = IN_RUN,
  resolution = { value: 'a word', value_type: 'text' }, withNote = false, answered = true, entity = 'agent_request', course = null,
  ref = `accept/${tag}/${label}`, filed = null, schema = DECISION_SCHEMA, appliedAt = null, field = null,
}) {
  const archived = by !== null;
  const itemState = state ?? (archived ? 'archived' : answered ? (kind === 'data_gap' && resolution?.dismissed ? 'dismissed' : 'resolved') : 'open');
  const row = await db.query(
    `insert into public.attention_items (id, raised_at, kind, course_id, entity, ref, field, state, resolved_at, resolution, resolution_note,
                                         applied_at, archived_at, archived_by, decision, decision_filed_at, decision_filed)
     values (coalesce($1::bigint, nextval(pg_get_serial_sequence('public.attention_items', 'id'))), $2::timestamptz, $3, $4, $5, $6, $7, $8,
             case when $9::boolean then $2::timestamptz + interval '1 minute' end,
             case when $9::boolean then $10::jsonb end,
             case when $11::boolean then 'a reason' end,
             $12::timestamptz,
             case when $13::boolean then $2::timestamptz + interval '4 minutes' end,
             case when $13::boolean then 'inbox-apply request ' || $14::text end,
             case when $13::boolean then jsonb_build_object('schema', $15::text, 'bucket', $16::text) end,
             case when $17::jsonb is null then null else $2::timestamptz + interval '1 hour' end,
             $17::jsonb)
     returning id`,
    [id, raisedAt, kind, course, entity, ref, field, itemState, answered, JSON.stringify(resolution), withNote, appliedAt, archived, by === null ? null : String(by), schema, bucket, filed === null ? null : JSON.stringify(filed)],
  );
  return row.rows[0].id;
}

