/** The four test questions as step 1 leaves them after the walk: the first two answered, all four of this run. */
async function raiseFour(more = {}) {
  const apply = await addApply();
  const confirm = await addItem({ label: 'confirm', by: apply, bucket: 'recorded_elsewhere', ...more.confirm });
  const dismiss = await addItem({ label: 'dismiss', kind: 'data_gap', by: apply, bucket: 'dismissed', resolution: { dismissed: true }, ...more.dismiss });
  const note = await addItem({ label: 'note', by: apply, withNote: true, ...more.note });
  const offline = await addItem({ label: 'offline', kind: 'data_gap', answered: false, ...more.offline });
  return { confirm, dismiss, note, offline };
}

const raisedParams = (items, more = {}) => ({
  confirm_item: String(items.confirm), dismiss_item: String(items.dismiss), note_item: String(items.note), offline_item: String(items.offline), since: SINCE, ...more,
});

test('questions-raised: the four, raised in this run with the right kinds and labels, the first two answered with no reason, passes', async () => {
  const items = await raiseFour();
  const passed = await prove('questions-raised', raisedParams(items));
  assert.equal(passed.code, EXIT.pass, passed.why);
  assert.deepEqual(
    [passed.detail.items_found, passed.detail.shaped_and_raised_in_this_run, passed.detail.answers_right, passed.detail.run_tags],
    [4, 4, 2, 1],
  );
  // The 60 seconds are for a host clock that runs ahead of the database's.
  await db.query('update public.attention_items set raised_at = $1::timestamptz where id = $2', [JUST_BEFORE, items.offline]);
  assert.equal((await prove('questions-raised', raisedParams(items))).code, EXIT.pass);
  await questionsRaisedCase2();
});

/** Empties the tables the cases fill, and builds what the case needs on them. */
async function rebuilt(build) {
  await db.exec('truncate public.attention_items, public.agent_requests, public.inbox_apply_writes, public.inbox_apply_holds, public.bb_files restart identity');
  return build();
}

/** an old row, a wrong kind or label, another tag, a reason, a missing answer or a row that is not a test question fails */
async function questionsRaisedCase2() {
  const bad = async (why, change) => {
    const items = await rebuilt(() => raiseFour());
    await change(items);
    assert.equal((await prove('questions-raised', raisedParams(items))).code, EXIT.fail, why);
  };
  const set = (column, value, label) => (items) => db.query(`update public.attention_items set ${column} = $1 where id = $2`, [value, items[label]]);
  await bad('raised before the run', (items) => db.query('update public.attention_items set raised_at = $1::timestamptz where id = $2', [BEFORE_RUN, items.note]));
  await bad('dismiss raised as a stack_must_confirm', set('kind', 'stack_must_confirm', 'dismiss'));
  await bad('confirm raised as a data_gap', set('kind', 'data_gap', 'confirm'));
  await bad('the third is labelled as the second', set('ref', `accept/${TAG}/dismiss`, 'note'));
  await bad('another run tag', set('ref', `accept/${OTHER_TAG}/offline`, 'offline'));
  await bad('confirmed with a reason', set('resolution_note', 'a reason', 'confirm'));
  await bad('dismissed with a reason', set('resolution_note', 'a reason', 'dismiss'));
  await bad('confirm never answered', (items) => db.query('update public.attention_items set resolved_at = null, resolution = null where id = $1', [items.confirm]));
  await bad('dismiss answered with a value, not dismissed', (items) => db.query(`update public.attention_items set resolution = '{"value": "x"}'::jsonb where id = $1`, [items.dismiss]));
  await bad('a row of a course', set('course_id', 'ist323', 'offline'));
  await bad('an item that is no test question', set('ref', 'sync-login-required', 'offline'));
  // A row that is not there is no row.
  const items = await rebuilt(() => raiseFour());
  const missing = await prove('questions-raised', raisedParams(items, { offline_item: '999999' }));
  assert.equal(missing.code, EXIT.fail);
  assert.equal(missing.detail.items_found, 3);
}

