  await bad('the apply request was never taken', () => afterSync({ apply: { claimedBy: 'a-session' } }));
  await bad('the apply request failed', () => afterSync({ apply: { state: 'failed', error: 'cli_error' } }));
  await bad('two apply requests name the sync', () => afterSync().then(async (w) => { await addApply({ trigger: 'sync', after: w.sync }); return w; }));
