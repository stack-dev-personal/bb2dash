const LOGIN_RAISED = { label: 'x', ref: 'sync-login-required', entity: 'agent_request', answered: false };

test("sync-taken: this run's sync, claimed by the sync container, passes; blocked, not failed, when it closed on a dead Blackboard login", async () => {
  const sync = await addSync();
  const passed = await prove('sync-taken', { request: String(sync), since: SINCE });
  assert.equal(passed.code, EXIT.pass, passed.why);
  assert.deepEqual(
    { ...passed.detail, created_at: null, claimed_at: null, finished_at: null },
    {
      request_id: sync, request_kind: 'sync', request_state: 'done', created_at: null, claimed_at: null, claimed_by: 'sync-runner', finished_at: null,
      asked_in_this_run: true, taken_by_the_runner: true, login_item_raised_in_this_run: false,
    },
  );
  const params = (request) => ({ request: String(request), since: SINCE });
  // Taken by a session or by nobody, from before the run, or not a sync: no.
  assert.equal((await prove('sync-taken', params(await addSync({ claimedBy: 'a-session' })))).code, EXIT.fail);
  assert.equal((await prove('sync-taken', params(await addRequest({ kind: 'sync', state: 'queued' })))).code, EXIT.fail);
  assert.equal((await prove('sync-taken', params(await addSync({ createdAt: BEFORE_RUN })))).code, EXIT.fail);
  assert.equal((await prove('sync-taken', params(await addApply()))).code, EXIT.fail);
  assert.equal((await prove('sync-taken', params(999))).detail.error, 'expected_one_row');
  // The sync closed failed and the login item was raised in this run: the login is dead, the run is repeated.
  // Taken is all this proof says: a sync that failed for another reason is judged by the next step.
  const dead = await addSync({ state: 'failed' });
  assert.equal((await prove('sync-taken', params(dead))).code, EXIT.pass);
  await addItem({ ...LOGIN_RAISED, raisedAt: IN_RUN });
  const blocked = await prove('sync-taken', params(dead));
  assert.deepEqual([blocked.code, blocked.blocked, blocked.detail.login_item_raised_in_this_run], [EXIT.blocked, true, true]);
  // A login item from before the run says nothing about this one.
  await db.query('update public.attention_items set raised_at = $1::timestamptz', [BEFORE_RUN]);
  assert.equal((await prove('sync-taken', params(dead))).code, EXIT.pass);
});

